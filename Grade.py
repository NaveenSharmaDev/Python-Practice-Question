Percentage =float(input("Enter your percentage: "))
if Percentage >= 90:
    print("Grade: A+")
elif Percentage >= 80:
    print("Grade: A")
elif Percentage >= 70:
    print("Grade: B")
elif Percentage >= 60:
    print("Grade: C")
elif Percentage >= 50:
    print("Grade: D")
elif Percentage >= 35:
    print("Grade: E")
else:
    print("Grade: Fail")
    